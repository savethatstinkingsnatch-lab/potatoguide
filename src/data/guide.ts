export function varietiesFor(climate: ClimateId, crop: CropId): Variety[] {
  return VARIETIES.filter((v) => v.crop === crop && v.climates.includes(climate)).sort(
    (a, b) => a.days[0] - b.days[0],
  );
}

export function cropLabel(crop: CropId): string {
  return crop === "potato" ? "Potato" : "Sweet potato";
}
